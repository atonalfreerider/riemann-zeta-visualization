#!/usr/bin/env python3
"""
Data for section R (the digits of τ and the primes): writes Assets/Tour/TauDigitsData.cs.

  python3 Tools/tau_digits_data.py

* Base30: the first 3000 base-30 digits of τ's fraction (τ = 6.283… = 6 + 8/30 + 14/30² + …), one character each
  ('0'–'9', 'a'–'t' for 10–29): E8's clock has 30 hours, so these are τ's digits read as hours.
* ReadPrime / ReadS / ReadDigits: what it costs to read each prime p ≤ 1000 out of τ's digits (section RB). With
  ζ(2k) = (τ/2)^(2k) T_k / (2 (4^k − 1)(2k − 1)!) (T_k the tangent numbers, integers), D digits of τ give log ζ(s) for
  every even s; take away the primes already read and what is left is p^(−s)(1 + R), R = Σ_{q > p} (p/q)^s + …, so
  p ≈ left^(−1/s). The readout takes p at the first even s where that estimate sits within 10^−3 of a whole number and
  moved less than 10^−4 since s − 2; it needs left ≈ p^(−s) above 10^(8 − D): D = ⌈s log₁₀ p + 8⌉. The full readout at
  D = 50, 100, 200, 400, 800, 1600, 3200 digits read 4, 9, 12, 25, 32, 51 and 80 primes, every one right, as this
  model predicts.
"""
import math
import mpmath
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Assets/Tour/TauDigitsData.cs"


def primes(n):
    s = bytearray([1]) * (n + 1)
    s[0] = s[1] = 0
    for i in range(2, int(n ** .5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n + 1) if s[i]]


def base30_digits(count):
    mpmath.mp.dps = int(count * math.log10(30)) + 40
    tau = 2 * mpmath.pi
    x = int(mpmath.floor((tau - 6) * mpmath.mpf(30) ** count))
    out = []
    for _ in range(count):
        x, r = divmod(x, 30)
        out.append(r)
    return out[::-1]


def read_cost(pr, i):
    """(s, digits of τ) the readout needs for pr[i] once the smaller primes are read."""
    p = pr[i]
    prev = None
    s = 2
    while True:
        rest = 0.0
        for q in pr[i + 1:]:
            t = (p / q) ** s
            rest += t
            if t < 1e-18 * rest:
                break
        rest += sum(p ** (-(m - 1) * s) / m for m in range(2, 6))
        est = p * (1 + rest) ** (-1 / s)
        r = round(est)
        if prev is not None and abs(est - r) < 1e-3 and abs(est - prev) < 1e-4:
            return s, math.ceil(s * math.log10(p) + 8)
        prev = est
        s += 2


def main():
    d30 = base30_digits(3000)
    assert d30[:6] == [8, 14, 26, 0, 2, 28]
    chars = "".join("0123456789abcdefghijklmnopqrst"[d] for d in d30)
    pr = primes(20000)
    rows = [(p, *read_cost(pr, i)) for i, p in enumerate(pr) if p <= 1000]
    lines = [
        "// Generated by Tools/tau_digits_data.py: do not edit by hand.",
        "/// <summary>Section R: τ's first base-30 digits, and what each prime ≤ 1000 costs to read out of τ's digits.</summary>",
        "public static class TauDigitsData",
        "{",
        "    /// <summary>The first 3000 base-30 digits of τ's fraction: '0'–'9', 'a'–'t' for 10–29.</summary>",
        f"    public const string Base30 = \"{chars}\";",
        "    /// <summary>The primes up to 1000, in order.</summary>",
        "    public static readonly int[] ReadPrime = { " + ", ".join(str(r[0]) for r in rows) + " };",
        "    /// <summary>The even s at which the readout takes each prime.</summary>",
        "    public static readonly int[] ReadS = { " + ", ".join(str(r[1]) for r in rows) + " };",
        "    /// <summary>The digits of τ the readout needs for each prime, once the smaller ones are read.</summary>",
        "    public static readonly int[] ReadDigits = { " + ", ".join(str(r[2]) for r in rows) + " };",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    run = 0
    for p, s, d in rows:
        run = max(run, d)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(chars)} base-30 digits, {len(rows)} primes (the dearest: "
          f"{max(rows, key=lambda r: r[2])})")


if __name__ == "__main__":
    main()
