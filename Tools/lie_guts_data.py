#!/usr/bin/env python3
"""Data for the 'Inside the Lie group' sections (IA–ID of docs/experiments/README.md), written to
Assets/Tour/LieGutsData.cs:

* the spoke charges of the zeta chain restricted to E8's exponent hours (n prime to 30) at t = 5000: the jump across
  spoke k (n = 30t/2πk), divided by Γ(1−s) e^(iπ(1−s)/2) (2πk/30)^(s−1)/30, for k = 1 … 30 (they approach tr(C^k));
* the Sato–Tate angles θ_p of Ramanujan's Δ = (θ_E8³ − E6²)/1728 for the primes p ≤ 20000:
  τ(p) = 2 p^(11/2) cos θ_p, with τ from 756 τ(n) = 65 σ11(n) + 691 σ5(n) − 691·252 Σ_{k<n} σ5(k) σ5(n−k).

Needs mpmath. Run from the repository root:  python3 Tools/lie_guts_data.py
"""
import cmath, math
from math import gcd
import mpmath as mp


def spoke_charges(t=5000.0, kmax=30):
    s = complex(0.5, t)
    ge = complex(mp.gamma(mp.mpc(0.5, -t)) * mp.exp(1j * mp.pi * (1 - mp.mpc(0.5, t)) / 2))
    n_max = int(30 * t / math.pi) + 200
    partial = [0j] * (n_max + 1)
    acc = 0j
    for n in range(1, n_max + 1):
        if gcd(n, 30) == 1:
            acc += cmath.exp(-s * math.log(n))
        partial[n] = acc

    def smooth(x, w=15):
        a, b = max(1, int(x) - w), min(n_max, int(x) + w)
        return sum(partial[a:b + 1]) / (b - a + 1)

    out = []
    for k in range(1, kmax + 1):
        a = 30 * t / (2 * math.pi * (k + .5))
        b = 30 * t / (2 * math.pi * (k - .5))
        jump = smooth(b) - smooth(a)
        unit = ge * (2 * math.pi * k / 30) ** (s - 1) / 30
        out.append(jump / unit)
    return out


def sato_tate(limit=20000):
    s5 = [0] * (limit + 1)
    s11 = [0] * (limit + 1)
    for d in range(1, limit + 1):
        d5, d11 = d ** 5, d ** 11
        for m in range(d, limit + 1, d):
            s5[m] += d5
            s11[m] += d11

    def tau(n):
        v = 65 * s11[n] + 691 * s5[n] - 691 * 252 * sum(s5[k] * s5[n - k] for k in range(1, n))
        assert v % 756 == 0
        return v // 756

    primes = [p for p in range(2, limit + 1) if all(p % q for q in range(2, int(p ** .5) + 1))]
    return [(p, math.acos(tau(p) / (2 * p ** 5.5))) for p in primes]


def main():
    charges = spoke_charges()
    angles = sato_tate()
    lines = [
        "// Generated by Tools/lie_guts_data.py: do not edit by hand.",
        "public static class LieGutsData",
        "{",
        "    /// <summary>Spoke charges of the gold chain (n prime to 30) at t = 5000, k = 1 … 30: real and imaginary parts.</summary>",
        "    public static readonly float[] SpokeChargeRe = { " + ", ".join(f"{c.real:.4f}f" for c in charges) + " };",
        "    public static readonly float[] SpokeChargeIm = { " + ", ".join(f"{c.imag:.4f}f" for c in charges) + " };",
        "",
        "    /// <summary>The primes p ≤ 20000 and the Sato–Tate angles θ_p of Δ: τ(p) = 2 p^(11/2) cos θ_p.</summary>",
        "    public static readonly int[] Primes = { " + ", ".join(str(p) for p, _ in angles) + " };",
        "    public static readonly float[] DeltaAngles = { " + ", ".join(f"{a:.5f}f" for _, a in angles) + " };",
        "}",
        "",
    ]
    with open("Assets/Tour/LieGutsData.cs", "w") as f:
        f.write("\n".join(lines))
    print(f"wrote Assets/Tour/LieGutsData.cs: {len(charges)} spoke charges, {len(angles)} Sato–Tate angles")


if __name__ == "__main__":
    main()
