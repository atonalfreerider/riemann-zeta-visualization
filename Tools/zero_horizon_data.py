#!/usr/bin/env python3
"""Data for section OD of docs/experiments/README.md ("How far the zeros see"), written to Assets/Tour/ZeroHorizonData.cs.

The explicit formula rebuilds Λ(n) from the zeros of ζ (section JB): with the first K zeros (up to height T = γ_K) and a
Gaussian taper e^(−γ²/2σ²), σ = T/4,
    Λ̂(n) = √n √τ/σ · ( √n e^(1/8σ²) − n^(−5/2)/(1 − n^(−2)) − Σ_{k≤K} 2 e^(−γ_k²/2σ²) cos(γ_k log n) ),
the second term being the trivial zeros'. The horizon x*(K) is the last n before the first integer whose Λ̂ is off by
more than 0.3 (log 2 = 0.69 separates a prime power's tooth from none). Written: Λ̂(n) for n ≤ NMax at 24 values of K
from 10 to 10 000 (as hundredths, in shorts), the heights T and the horizons.

Run from the repository root:  python3 Tools/zero_horizon_data.py   (zeros from Assets/Resources/zetazeros.txt; seconds)
"""
import math, os
from multiprocessing import Pool

OUT = os.path.join("Assets", "Tour", "ZeroHorizonData.cs")
TAU = 2 * math.pi
Z = [float(l.split()[1]) for l in open(os.path.join("Assets", "Resources", "zetazeros.txt")) if l.strip()]
NMAX = 1100
KS = sorted(set(round(10 * 1000 ** (i / 23)) for i in range(24)))


def lam(n):
    m = n
    for p in range(2, int(n ** .5) + 1):
        if m % p == 0:
            while m % p == 0:
                m //= p
            return math.log(p) if m == 1 else 0.0
    return math.log(n)


LAM = [0.0, 0.0] + [lam(n) for n in range(2, NMAX + 1)]


def teeth(K):
    sig = Z[K - 1] / 4
    w = [2 * math.exp(-g * g / (2 * sig * sig)) for g in Z[:K]]
    out = []
    for n in range(2, NMAX + 1):
        u = math.log(n)
        s = sum(wk * math.cos(gk * u) for wk, gk in zip(w, Z[:K]))
        triv = n ** -2.5 / (1 - n ** -2.0)
        out.append(math.sqrt(n * TAU) / sig * (math.sqrt(n) * math.exp(1 / (8 * sig * sig)) - triv - s))
    return out


def main():
    assert len(KS) == 24, KS
    with Pool(8) as pool:
        rows = pool.map(teeth, KS)
    horizon = []
    for K, row in zip(KS, rows):
        bad = [n for n, v in zip(range(2, NMAX + 1), row) if abs(v - LAM[n]) > .3]
        horizon.append(bad[0] - 1 if bad else NMAX)
        print(f"K = {K:5}  T = {Z[K - 1]:8.1f}  horizon {horizon[-1]:5}  ({horizon[-1] / (Z[K - 1] / TAU):.2f} t/τ)")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by Tools/zero_horizon_data.py: the prime powers rebuilt from the first K zeros of ζ, for section OD of\n")
        f.write("// docs/experiments/README.md. Do not edit by hand.\n")
        f.write("public static class ZeroHorizonData\n{\n")
        f.write(f"    public const int NMax = {NMAX};\n")
        f.write("    /// <summary>The numbers of zeros used, the height of the last one, and the horizon: every n ≤ Horizon[i] is rebuilt\n")
        f.write("    /// to within 0.3 of Λ(n).</summary>\n")
        f.write("    public static readonly int[] K = { " + ", ".join(str(k) for k in KS) + " };\n")
        f.write("    public static readonly float[] T = { " + ", ".join(f"{Z[k - 1]:.2f}f" for k in KS) + " };\n")
        f.write("    public static readonly int[] Horizon = { " + ", ".join(str(h) for h in horizon) + " };\n")
        f.write("    /// <summary>Λ̂(n) in hundredths, row i (K[i] zeros) holding n = 2 … NMax.</summary>\n")
        f.write("    public static readonly short[] Teeth = { " + ", ".join(str(max(-32000, min(32000, round(100 * v)))) for row in rows for v in row) + " };\n")
        f.write("}\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
