#!/usr/bin/env python3
"""Data for "A race between the families" (section MC of docs/experiments/README.md), written to
Assets/Tour/FamilyRaceData.cs.

The primes p != 23 fall into three classes by how x^3 - x - 1 splits mod p, which is how they act on its three roots: the
Frobenius of p in S3, the Galois group of the splitting field (the Hilbert class field of Q(sqrt -23)).
  identity (3 roots)       p = x^2 + xy + 6y^2, the principal family      share 1/6   a_p =  2
  3-cycles (no root)       p = 2x^2 +- xy + 3y^2, the second family       share 1/3   a_p = -1
  reflections (one root)   on neither family, (-23/p) = -1                share 1/2   a_p =  0
with a_p the coefficients of eta(z) eta(23z) = q prod (1 - q^n)(1 - q^23n), computed here from Euler's pentagonal series.

E_C(x) = (log x/sqrt x)((6/|C|) pi(x; C) - pi*(x)) for each class C (pi* = the primes other than 23). Squaring in S3 sends
the three reflections and the identity to the identity, and each 3-cycle to the other one, so the explicit formula predicts
the means -(r(C)/|C| - 1) with r(C) = #{g : g^2 in C}: -3 for the principal family, 0 for the second, +1 for the inert primes,
the same pattern as E8's spokes mod 30 (section MA). The fair race counts each prime power p^k as 1/k in the class of
Frob(p)^k.

Run from the repository root:  python3 Tools/family_race_data.py   (about a minute).
"""
import array, math, os

OUT = os.path.join("Assets", "Tour", "FamilyRaceData.cs")
N = 10 ** 7


def main():
    sieve = bytearray([1]) * (N + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(N ** .5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(range(i * i, N + 1, i)))
    # q eta(z) eta(23z) = sum c(n) q^n: Euler's pentagonal series twice
    pent = []
    k = 0
    while True:
        done = True
        for kk in ((k,) if k == 0 else (k, -k)):
            p = kk * (3 * kk - 1) // 2
            if p <= N:
                pent.append((p, -1 if kk % 2 else 1))
                done = False
        if done:
            break
        k += 1
    c = array.array("b", bytes(N + 1))
    for p1, s1 in pent:
        for p2, s2 in pent:
            n = 1 + p1 + 23 * p2
            if n > N:
                continue
            c[n] += s1 * s2
    assert [c[n] for n in (1, 2, 3, 4, 5, 6)] == [1, -1, -1, 0, 0, 1], [c[n] for n in range(1, 8)]
    # classes: 0 identity (principal family), 1 three-cycles (second family), 2 reflections (inert)
    cls_of = {2: 0, -1: 1, 0: 2}
    size = [1, 2, 3]
    xs = [int(round(10 ** (2 + 5 * k / 1999))) for k in range(2000)]
    cnt = [0, 0, 0]
    pw = [0.0, 0.0, 0.0]
    tot, ptot = 0, 0.0
    E = [[], [], []]
    F = [[], [], []]
    powers = {}
    for q in range(2, int(N ** .5) + 1):
        if sieve[q] and q != 23:
            cq = cls_of[c[q]]
            m, j, cl = q * q, 2, cq
            while m <= N:
                # the class of Frob(q)^j in S3: a 3-cycle cubed and a reflection squared are the identity
                if cq == 1:
                    cl_j = 0 if j % 3 == 0 else 1
                elif cq == 2:
                    cl_j = 0 if j % 2 == 0 else 2
                else:
                    cl_j = 0
                powers[m] = (cl_j, 1.0 / j)
                m *= q
                j += 1
    i = 0
    for n in range(2, N + 1):
        if sieve[n] and n != 23:
            cl = cls_of.get(c[n])
            assert cl is not None, (n, c[n])
            cnt[cl] += 1
            tot += 1
        elif n in powers:
            cl, w = powers[n]
            pw[cl] += w
            ptot += w
        while i < len(xs) and xs[i] == n:
            f = math.log(n) / math.sqrt(n)
            for k in range(3):
                E[k].append(f * (6 / size[k] * cnt[k] - tot))
                F[k].append(f * (6 / size[k] * (cnt[k] + pw[k]) - tot - ptot))
            i += 1
    names = ["principal family", "second family", "inert primes"]
    print("primes up to 10^7 (not 23):", tot, dict(zip(names, cnt)), " shares", [round(x / tot, 4) for x in cnt])
    print("mean E_C:", [round(sum(e) / len(e), 2) for e in E], " predicted -3, 0, +1")
    ahead = [sum(1 for v in e if v > 0) / len(e) for e in E]
    print("share of log x with each class ahead of its share:", [round(a, 3) for a in ahead])
    print("fair race (p^k as 1/k): means", [round(sum(f) / len(f), 2) for f in F], " ahead", [round(sum(1 for v in f if v > 0) / len(f), 3) for f in F])
    lead = [0, 0, 0]
    for k in range(len(xs)):
        lead[max(range(3), key=lambda j: E[j][k])] += 1
    print("in the lead:", [round(l / len(xs), 3) for l in lead])
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by Tools/family_race_data.py: the race between the three Frobenius classes of x^3 - x - 1 (the families\n")
        f.write("// of discriminant -23) to 10^7, for section MC of docs/experiments/README.md. Do not edit by hand.\n")
        f.write("public static class FamilyRaceData\n{\n")
        f.write("    /// <summary>log₁₀ x of the samples: 2000 points from 2 to 7.</summary>\n")
        f.write("    public const float Log0 = 2f, LogStep = 5f / 1999f; public const int Count = 2000;\n")
        f.write("    /// <summary>E_C(x) for C = the principal family, the second family, the inert primes (3 × 2000).</summary>\n")
        f.write("    public static readonly float[] Race = { " + ", ".join(f"{v:.3f}f" for e in E for v in e) + " };\n")
        f.write("    /// <summary>The same with every prime power p^k counted as 1/k in the class of Frob(p)^k.</summary>\n")
        f.write("    public static readonly float[] Fair = { " + ", ".join(f"{v:.3f}f" for e in F for v in e) + " };\n")
        f.write("    /// <summary>Primes up to 10⁷ in each class; share of log x ahead of its share, measured, for each class.</summary>\n")
        f.write("    public static readonly int[] Primes = { " + ", ".join(map(str, cnt)) + " };\n")
        f.write("    public static readonly float[] Ahead = { " + ", ".join(f"{a:.4f}f" for a in ahead) + " };\n")
        small = [q for q in range(2, int(N ** .5) + 1) if sieve[q] and q != 23]
        f.write("    /// <summary>The primes up to √10⁷ (not 23) and their classes (0 principal, 1 second family, 2 inert), for the fold.</summary>\n")
        f.write("    public static readonly int[] SmallPrimes = { " + ", ".join(map(str, small)) + " };\n")
        f.write("    public static readonly byte[] SmallClasses = { " + ", ".join(str(cls_of[c[q]]) for q in small) + " };\n")
        f.write("}\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
