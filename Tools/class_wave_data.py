#!/usr/bin/env python3
"""The two families' completed zeta functions on the critical line for D = -23, for deriving the mixtures' curve on
screen (the long-form segment on discovery 4), written to Assets/Tour/ClassWaveData.cs.

On Re s = 1/2 every family's completed zeta function Lambda_f(1/2 + it) is real. Their values come from the cache that
Tools/class_group_data.py --cache DIR keeps (edges23.json: Lambda_e and Lambda_c at t = 0.02, 0.04, ..., 50). Both are
divided by the same positive envelope |(sqrt 23 / 2 pi)^s Gamma(s)| at s = 1/2 + it, so they read as waves of steady
size; the ratio R(t) = -Lambda_e / Lambda_c (ClassGroupData.MixR) is unchanged by it.

  python3 Tools/class_wave_data.py CACHE_DIR
"""
import json, math, os, sys

OUT = os.path.join("Assets", "Tour", "ClassWaveData.cs")


def main():
    cache = sys.argv[1]
    vl = json.load(open(os.path.join(cache, "edges23.json")))[0]
    step = 2                      # every 0.04 in t
    E, C, T = [], [], []
    for k in range(0, len(vl), step):
        t = 0.02 * k + 0.02
        env = math.sqrt(math.sqrt(23) / (2 * math.pi)) * math.sqrt(math.pi / math.cosh(math.pi * t))
        e, c = vl[k][0][0] / env, vl[k][1][0] / env
        T.append(t); E.append(e); C.append(c)
    # checks: the ratio matches the stored curve, and the sign changes of e are the first family's zeros on the line
    zeros = [T[i] + (T[i + 1] - T[i]) * E[i] / (E[i] - E[i + 1]) for i in range(len(E) - 1) if E[i] * E[i + 1] < 0]
    print(f"{len(T)} samples; first family's zeros on the line from the samples: {', '.join(f'{z:.3f}' for z in zeros[:6])} …")
    top = max(max(abs(x) for x in E), max(abs(x) for x in C))
    print(f"largest normalised value {top:.2f}")
    with open(OUT, "w") as f:
        f.write("// Generated by Tools/class_wave_data.py from Tools/class_group_data.py's cache. Do not edit by hand.\n")
        f.write("/// <summary>D = −23 on Re s = ½: the two families' completed zeta functions, divided by one positive envelope.</summary>\n")
        f.write("public static class ClassWaveData\n{\n")
        f.write(f"    public const float T0 = 0.02f, TStep = {0.02 * step:.2f}f;\n")
        f.write("    /// <summary>Λ of x² + xy + 6y² (the first family).</summary>\n")
        f.write("    public static readonly float[] E = { " + ", ".join(f"{x:.4g}f" for x in E) + " };\n")
        f.write("    /// <summary>Λ of 2x² ± xy + 3y² (the second family).</summary>\n")
        f.write("    public static readonly float[] C = { " + ", ".join(f"{x:.4g}f" for x in C) + " };\n")
        f.write("}\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
